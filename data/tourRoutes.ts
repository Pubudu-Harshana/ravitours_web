// Fallback helper to generate a route for any tour dynamically
export function getRouteForTour(slug: string, tourTitle?: string): TourRouteData {
  if (tourRoutesMap[slug]) {
    return tourRoutesMap[slug];
  }

  // Fallback to default Sri Lanka Highlights circuit if custom slug
  const fallback = tourRoutesMap["sri-lanka-highlights"];
  return {
    ...fallback,
    tourSlug: slug,
    tourTitle: tourTitle || fallback.tourTitle,
  };
}
